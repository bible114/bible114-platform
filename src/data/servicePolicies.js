export const getPolicyIdsForAudience = (audience = 'member') => (
    POLICY_AUDIENCE_IDS[audience] || POLICY_AUDIENCE_IDS.member
);

export const createEmptyPolicyConsents = (audience = 'member') => Object.fromEntries(
    getPolicyIdsForAudience(audience).map(id => [id, false])
);

export const isPolicyConsentComplete = (consents = {}, audience = 'member') => (
    getPolicyIdsForAudience(audience).every(id => consents[id] === true)
);
